/**
 * A signed whole number, e.g. « +30 » or « −12 ».
 *
 * The typographic minus (U+2212), not the hyphen: it aligns with the digits.
 */
function signed(value: number): string {
  return `${value > 0 ? '+' : '\u2212'}${Math.abs(value)}`
}

